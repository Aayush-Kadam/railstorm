import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

const browser = await chromium.launch({headless:true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH}:{})});
const page = await browser.newPage({viewport:{width:1440,height:1100}, reducedMotion:'reduce'});
const failures=[];
let committedFrames=0;
let settledFrames=0;
page.on('websocket', socket=>socket.on('framereceived',frame=>{committedFrames++;const batch=JSON.parse(String(frame.payload));if(batch.events?.some(e=>e.event_type==='PAYMENT_CHANGED'&&e.payload.economic_status==='SETTLED'))settledFrames++;}));
page.on('pageerror', e=>failures.push(e.message));
await page.goto(process.env.RAILSTORM_URL || 'http://127.0.0.1:8840');
const health=await (await page.request.get(new URL('/api/v1/health',page.url()).href)).json();
assert.equal(health.engine,'0.1.1');
await page.getByRole('button',{name:/Scenarios/}).click();
await page.getByRole('button',{name:'Validate & create run'}).click();
await page.getByRole('button',{name:'Step',exact:true}).waitFor();
await page.waitForFunction(()=>document.querySelector('.status')?.textContent==='READY');
await page.getByRole('button',{name:'Step',exact:true}).click();
await page.getByRole('button',{name:'p000000 ↗'}).waitFor();
await page.getByRole('button',{name:'Run',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.status')?.textContent==='COMPLETED');
await page.getByRole('button',{name:'p000000 ↗'}).click();
await page.getByText('Journal effects · integer minor units').waitFor();
assert(await page.getByRole('cell',{name:'-500020000',exact:true}).count()===1);
assert(await page.getByRole('cell',{name:'665000000',exact:true}).count()===1);
await page.getByRole('button',{name:/Audit/}).click();
await page.getByRole('button',{name:'Verify replay'}).click();
await page.waitForFunction(()=>document.querySelector('.verification')?.textContent?.includes('"match": true'));
await page.getByRole('button',{name:'Reconcile',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.verification')?.textContent?.includes('"financial_errors": 0'));
const downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Export JSON'}).click();
const download=await downloadPromise;
assert(download.suggestedFilename().endsWith('.json'));
await page.getByRole('button',{name:/Network/}).click();
await page.locator('.network canvas').first().waitFor();
fs.mkdirSync('../docs/screenshots',{recursive:true});
await page.screenshot({path:'../docs/screenshots/command-center-desktop.png',fullPage:true});
// A fresh crisis fixture exercises actual fault scheduling and activation through UI controls.
await page.getByRole('button',{name:/Scenarios/}).click();
await page.locator('select').filter({has:page.locator('option[value="healthy"]')}).selectOption('healthy');
await page.getByRole('button',{name:'Validate & create run'}).click();
await page.waitForFunction(()=>document.querySelector('.status')?.textContent==='READY');
await page.getByRole('button',{name:/Chaos/}).click();
await page.getByRole('button',{name:'Schedule fault'}).click();
await page.getByText('Fault scheduled. Step or Run to observe its effects.').waitFor();
await page.getByRole('button',{name:'Run',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.status')?.textContent==='COMPLETED', {timeout:60000});
await page.getByText('CRASH_AFTER_COMMIT',{exact:true}).last().waitFor();
const persistedRun=await page.getByRole('combobox',{name:'Persisted run'}).inputValue();
await page.reload();
await page.getByRole('combobox',{name:'Persisted run'}).waitFor();
await page.waitForFunction(id=>document.querySelector('select[aria-label="Persisted run"]')?.value===id,persistedRun);
assert.equal(await page.getByRole('combobox',{name:'Persisted run'}).inputValue(),persistedRun);
await page.waitForFunction(()=>document.querySelector('.status')?.textContent==='COMPLETED');
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:/Scenarios/}).click();
assert(await page.getByRole('button',{name:'Validate & create run'}).isVisible());
await page.keyboard.press('Tab');
assert(await page.evaluate(()=>document.activeElement!==document.body));
await page.screenshot({path:'../docs/screenshots/command-center-mobile.png',fullPage:true});
assert.deepEqual(failures,[]);
assert(committedFrames>0,'Actual server must deliver committed WebSocket event frames');
assert(settledFrames>0,'Actual server must stream a committed SETTLED payment');
const evidence={passed:1,engine:health.engine, workflow:'create, step, run, inspect journal, replay, reconcile, export, schedule fault, reload, mobile, keyboard, reduced motion',pageErrors:failures,committedWebSocketFrames:committedFrames,settledFrames};
fs.writeFileSync('../docs/p01-browser-observed.json',JSON.stringify(evidence,null,2));
console.log(JSON.stringify(evidence));
await browser.close();
